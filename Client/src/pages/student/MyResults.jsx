import { useEffect, useMemo, useState } from "react";
import { supabase } from "../../lib/supabase";
import { useAuth } from "../../context/AuthContext";
import { Button } from "../../components/ui";
import { gradeFor } from "../../lib/status";
import { BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer } from "recharts";
import { chartAxis, chartTooltip } from "../../components/charts/ChartsConfig";
import { Card, Empty, StatCard } from "../../components/ui";
import DashboardHeader from "../../components/dashboard/DashboardHeader";

// chartAxis config reused, with the tick size raised to the 11px text floor
const axis = { ...chartAxis, tick: { ...chartAxis.tick, fontSize: 11 } };

const downloadSheet = (sheet, rows, student) => {
  const win = window.open("", "_blank", "width=880,height=960");
  if (!win) {
    alert("Popup blocked. Please allow popups for this site to download results.");
    return;
  }
  const examName = sheet.exams?.name ?? "Result";
  const year = sheet.exams?.academic_year ?? null;
  const got = rows.reduce((s, i) => s + Number(i.marks_obtained), 0);
  const max = rows.reduce((s, i) => s + Number(i.max_marks), 0);
  const pct = max > 0 ? Math.round((got / max) * 1000) / 10 : 0;
  const issued = new Date(sheet.published_at).toLocaleDateString();

  const bodyRows = rows
    .map((i) => {
      const p = Number(i.max_marks) > 0 ? (Number(i.marks_obtained) / Number(i.max_marks)) * 100 : 0;
      return `<tr>
        <td>${i.subjects?.code ?? ""}</td>
        <td>${i.subjects?.name ?? ""}</td>
        <td class="num">${i.marks_obtained}</td>
        <td class="num">${i.max_marks}</td>
        <td class="num">${Math.round(p)}%</td>
        <td class="num grade">${gradeFor(p)}</td>
      </tr>`;
    })
    .join("");

  win.document.write(`<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<title>${examName}${year ? ` (${year})` : ""} — Result</title>
<style>
  * { margin: 0; padding: 0; box-sizing: border-box; }
  body { font-family: Georgia, "Times New Roman", serif; color: #111827; padding: 40px; }
  .head { display: flex; justify-content: space-between; align-items: flex-end; border-bottom: 3px solid #4f46e5; padding-bottom: 14px; }
  .brand { font-size: 26px; letter-spacing: 0.5px; }
  .brand small { display: block; font-size: 11px; letter-spacing: 2px; text-transform: uppercase; color: #6b7280; margin-top: 3px; }
  .muted { color: #6b7280; font-size: 11px; }
  h1 { font-size: 20px; margin: 26px 0 4px; font-weight: 500; }
  table { width: 100%; border-collapse: collapse; margin-top: 18px; font-size: 13px; }
  th, td { border: 1px solid #e5e7eb; padding: 8px 10px; text-align: left; }
  th { background: #f3f4f6; font-size: 11px; text-transform: uppercase; letter-spacing: 1px; }
  .num { text-align: right; font-variant-numeric: tabular-nums; }
  .grade { color: #4f46e5; font-weight: bold; }
  .total td { font-weight: bold; background: #fafafa; }
  .stamp { margin-top: 30px; display: flex; justify-content: space-between; font-size: 11px; color: #6b7280; }
  .foot { margin-top: 40px; border-top: 1px solid #e5e7eb; padding-top: 10px; font-size: 11px; color: #9ca3af; text-align: center; }
  @media print { body { padding: 24px; } }
</style>
</head>
<body>
  <div class="head">
    <div class="brand">Gradia<small>Student Result Management System</small></div>
    <div class="muted">Issued ${issued}</div>
  </div>
  <h1>${examName}${year ? ` <span class="muted">· ${year}</span>` : ""}</h1>
  <p class="muted">Student: <strong>${student?.name ?? "—"}</strong> (${student?.username ?? "—"}) &nbsp;·&nbsp; Class: ${student?.classes?.name ?? "—"}</p>
  <table>
    <thead><tr><th>Code</th><th>Subject</th><th style="text-align:right">Marks</th><th style="text-align:right">Max</th><th style="text-align:right">%</th><th style="text-align:right">Grade</th></tr></thead>
    <tbody>
      ${bodyRows}
      <tr class="total"><td colspan="2">Total</td><td class="num">${got}</td><td class="num">${max}</td><td class="num">${Math.round(pct)}%</td><td class="num grade">${gradeFor(pct)}</td></tr>
    </tbody>
  </table>
  <div class="stamp"><span>Generated by Gradia · ${new Date().toLocaleString()}</span><span>Digitally generated document</span></div>
  <div class="foot">This score sheet is provisional until certified by the institution.</div>
</body>
</html>`);
  win.document.close();
  win.focus();
  win.print();
};

const MyResults = () => {
  const { profile } = useAuth();
  const [sheets, setSheets] = useState(null); // published sheets for my class; null = still loading
  const [items, setItems] = useState([]); // my result items across those sheets
  const [loadError, setLoadError] = useState(null);

  useEffect(() => {
    supabase
      .from("result_sheets")
      .select("id, published_at, exams ( name, academic_year )")
      .eq("status", "published")
      .order("published_at", { ascending: false })
      .then(({ data, error }) => {
        setSheets(data ?? []);
        if (error) setLoadError(`Could not load your results: ${error.message}. Refresh the page and try again.`);
      });
  }, []);

  useEffect(() => {
    const ids = (sheets ?? []).map((s) => s.id);
    if (ids.length === 0) {
      setItems([]);
      return;
    }
    supabase
      .from("result_items")
      .select("sheet_id, marks_obtained, max_marks, subjects ( name, code )")
      .in("sheet_id", ids)
      .order("sheet_id")
      .then(({ data, error }) => {
        setItems(data ?? []);
        if (error) setLoadError(`Could not load your marks: ${error.message}. Refresh the page and try again.`);
      });
  }, [sheets]);

  const total = useMemo(
    () => items.reduce((sum, i) => sum + Number(i.marks_obtained), 0),
    [items],
  );
  const totalMax = useMemo(
    () => items.reduce((sum, i) => sum + Number(i.max_marks), 0),
    [items],
  );
  const avgPercentage = totalMax > 0 ? Math.round((total / totalMax) * 1000) / 10 : null;

  const chartData = useMemo(
    () =>
      (sheets ?? [])
        .map((sheet, idx) => {
          const mine = items.filter((i) => i.sheet_id === sheet.id);
          const got = mine.reduce((s, i) => s + Number(i.marks_obtained), 0);
          const max = mine.reduce((s, i) => s + Number(i.max_marks), 0);
          return {
            exam: sheet.exams?.name ?? `Result ${idx + 1}`,
            score: max > 0 ? Math.round((got / max) * 1000) / 10 : 0,
          };
        })
        .reverse(),
    [sheets, items],
  );

  return (
    <>
      <DashboardHeader title="My Results" subtitle="Published results for your class." />

      {loadError ? (
        <p className="mt-6 rounded-lg border border-(--danger)/40 bg-(--danger-subtle) px-4 py-3 text-xs text-(--danger)">
          {loadError}
        </p>
      ) : sheets === null ? (
        <div className="mt-7 space-y-3" aria-hidden="true">
          <div className="grid gap-3 sm:grid-cols-3">
            {["published", "average", "grade"].map((k) => (
              <div key={k} className="glass-inner h-20 motion-safe:animate-pulse rounded-xl" />
            ))}
          </div>
          <div className="glass-inner h-40 motion-safe:animate-pulse rounded-xl" />
        </div>
      ) : (
        <>
      <div className="mt-7 grid gap-3 sm:grid-cols-3">
        <StatCard label="Published results" value={sheets.length} />
        <StatCard
          label="Overall average"
          value={avgPercentage !== null ? `${avgPercentage}%` : "—"}
        />
        <StatCard label="Overall grade" value={avgPercentage !== null ? gradeFor(avgPercentage) : "—"} />
      </div>

      {chartData.length > 0 && (
        <Card className="mt-4">
          <p className="text-xs font-medium text-(--muted-foreground)">
            Score per exam (%)
          </p>
          <div className="mt-3 h-55 w-full">
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={chartData} margin={{ top: 8, right: 8, left: -24, bottom: 0 }}>
                <CartesianGrid stroke="var(--border-subtle)" strokeDasharray="2 4" vertical={false} />
                <XAxis dataKey="exam" {...axis} dy={8} />
                <YAxis {...axis} domain={[0, 100]} ticks={[0, 25, 50, 75, 100]} width={35} />
                <Tooltip
                  cursor={{ fill: "color-mix(in srgb, var(--primary) 6%, transparent)" }}
                  {...chartTooltip}
                />
                <Bar dataKey="score" fill="var(--primary)" radius={[6, 6, 0, 0]} barSize={28} />
              </BarChart>
            </ResponsiveContainer>
          </div>
        </Card>
      )}

      <section className="mt-8 space-y-4">
        {sheets.length === 0 && <Empty>No published results yet. You’ll be notified when results go live.</Empty>}
        {sheets.map((sheet) => {
          const mine = items.filter((i) => i.sheet_id === sheet.id);
          const got = mine.reduce((s, i) => s + Number(i.marks_obtained), 0);
          const max = mine.reduce((s, i) => s + Number(i.max_marks), 0);
          const pct = max > 0 ? Math.round((got / max) * 1000) / 10 : 0;
          return (
            <Card key={sheet.id}>
              <div className="flex flex-wrap items-baseline justify-between gap-2">
                <p className="text-sm font-semibold text-(--foreground)">
                  {sheet.exams?.name}
                  {sheet.exams?.academic_year ? (
                    <span className="ml-2 font-normal text-(--muted-foreground)">{sheet.exams.academic_year}</span>
                  ) : null}
                </p>
                <div className="flex items-center gap-3">
                  <p className="text-xs text-(--muted-foreground)">
                    Published {new Date(sheet.published_at).toLocaleDateString()}
                  </p>
                  <Button
                    variant="subtle"
                    onClick={() => downloadSheet(sheet, mine, profile)}
                  >
                    Download PDF
                  </Button>
                </div>
              </div>
              <div className="-mx-5 overflow-x-auto px-5">
              <table className="mt-3 w-full min-w-[26rem] text-sm tabular-nums">
                <thead>
                  <tr className="text-left text-xs text-(--muted)">
                    <th className="py-1 font-medium">Subject</th>
                    <th className="py-1 font-medium">Marks</th>
                    <th className="py-1 font-medium">Max</th>
                    <th className="py-1 font-medium">%</th>
                    <th className="py-1 font-medium">Grade</th>
                  </tr>
                </thead>
                <tbody>
                  {mine.map((i) => {
                    const p = Number(i.max_marks) > 0 ? (Number(i.marks_obtained) / Number(i.max_marks)) * 100 : 0;
                    return (
                      <tr key={i.id ?? i.sheet_id + i.subject_id} className="border-t border-(--border-subtle)">
                        <td className="py-1.5 text-(--foreground)">
                          <span className="font-medium">{i.subjects?.code}</span> {i.subjects?.name}
                        </td>
                        <td className="py-1.5 tabular text-(--foreground)">{i.marks_obtained}</td>
                        <td className="py-1.5 tabular text-(--muted)">{i.max_marks}</td>
                        <td className="py-1.5 tabular text-(--muted)">{Math.round(p)}%</td>
                        <td className="py-1.5 text-(--primary)">{gradeFor(p)}</td>
                      </tr>
                    );
                  })}
                  <tr className="border-t border-(--border)">
                    <td className="py-2 text-(--foreground)">Total</td>
                    <td className="py-2 tabular font-medium text-(--foreground)">{got}</td>
                    <td className="py-2 tabular text-(--muted)">{max}</td>
                    <td className="py-2 font-medium text-(--foreground)">{Math.round(pct)}%</td>
                    <td className="py-2 font-medium text-(--primary)">{gradeFor(pct)}</td>
                  </tr>
                </tbody>
              </table>
              </div>
            </Card>
          );
        })}
        </section>
        </>
      )}
    </>
  );
};

export default MyResults;
